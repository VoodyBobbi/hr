_STEP_BY_FIELD = {field: (question, error) for field, question, error in ANKETA_STEPS}
_FIELD_ORDER_IN_ANKETA = [field for field, _, _ in ANKETA_STEPS]


def is_law_declined(text: str) -> bool:
    """Грубая проверка на явный отказ от согласия — не идеальный
    классификатор намерения (это было бы задачей для ИИ, которого мы здесь
    сознательно не используем), а простая проверка на несколько самых
    частых слов отказа. Всё, что НЕ совпало явно — считается продолжением
    (тем же принципом, что описан в system_prompt.md до этой правки:
    "Дождись, что кандидат явно продолжил диалог... кроме явного отказа")."""
    normalized = text.strip().lower()
    return any(keyword in normalized for keyword in LAW_DECLINE_KEYWORDS)


def get_next_step(candidate_id: str):
    """Возвращает (field_name, question) для следующего незаполненного поля
    анкеты, либо None, если все 29 полей уже заполнены (анкета готова к
    показу итоговой карточки на подтверждение)."""
    card = candidates.get_card(candidate_id)
    for field in _FIELD_ORDER_IN_ANKETA:
        if not card.get(field):
            return field, _STEP_BY_FIELD[field][0]
    return None


def process_answer(candidate_id: str, field: str, raw_answer: str):
    """Обрабатывает ответ кандидата на вопрос текущего поля.

    Возвращает кортеж (ok: bool, message: str):
    - ok=True  -> поле сохранено, message — текст СЛЕДУЮЩЕГО вопроса (или
      финальное сообщение, если это было последнее из 29 полей).
    - ok=False -> поле НЕ сохранено (не прошло валидацию), message —
      дружелюбный текст ошибки для ЭТОГО ЖЕ поля (тот же вопрос кандидату
      предстоит увидеть ещё раз в следующем сообщении бота — см.
      assistant.py, где вызывается эта функция)."""
    try:
        clean_value = validate_field(field, raw_answer)
    except FieldValidationError:
        _, friendly_error = _STEP_BY_FIELD[field]
        return False, friendly_error

    candidates.set_field(candidate_id, field, clean_value)

    next_step = get_next_step(candidate_id)
    if next_step is None:
        return True, None  # анкета полностью заполнена — дальше показ карточки, см. assistant.py
    _, next_question = next_step
    return True, next_question


def format_card_for_confirmation(candidate_id: str) -> str:
    """Формирует текст итоговой карточки анкеты для показа кандидату перед
    финальным подтверждением — тот же принцип, что раньше был в
    system_prompt.md ("Покажи ПОЛНУЮ карточку... попроси явного
    подтверждения ПЕРЕД CARD_CONFIRMED"), просто собран кодом из уже
    сохранённых полей, а не пересказан моделью по памяти (что исключает
    риск модели ошибочно исказить значение при пересказе)."""
    card = candidates.get_card(candidate_id)
    lines = ["Проверьте, пожалуйста, все данные:\n"]
    for field in _FIELD_ORDER_IN_ANKETA:
        lines.append(f"{field}: {card.get(field, '—')}")
    lines.append("\nВсё верно? Напишите «да» для подтверждения, либо укажите, что нужно исправить.")
    return "\n".join(lines)


def is_confirmation_yes(text: str) -> bool:
    """Та же логика, что is_law_declined, только в обратную сторону —
    простая проверка на явное согласие, не классификатор намерения."""
    normalized = text.strip().lower()
    return normalized in ("да", "верно", "всё верно", "все верно", "подтверждаю", "ок", "окей")


# --- Удаление данных по запросу кандидата (152-ФЗ, ст. 21) -----------------
#
# Раньше эту команду распознавал GigaChat (маркер DELETE_MY_DATA в
# assistant.py) — в промпт для этого уходил ПОЛНЫЙ ТЕКСТ сообщения
# кандидата. Здесь — та же идея, что и для остального в этом файле: простое
# сопоставление по ключевым словам, без обращения к ИИ и без передачи
# текста куда-либо. Раз сам факт "это похоже на просьбу удалить данные"
# полностью вычисляется здесь, кодом — финальное решение (переспросить
# второй раз, затем удалить) тоже принимает код, а не GigaChat: раз GigaChat
# ничего не добавляет к уже вычисленному факту, вызывать её здесь было бы
# бессмысленным сетевым запросом ради решения, которое уже принято.
_DELETE_REQUEST_KEYWORDS = (
    "удали мои данные", "удалить мои данные", "сотри мои данные",
    "удали меня", "удалить меня", "сотри меня",
    "удали анкету", "удалить анкету",
    "отозвать согласие", "отзываю согласие",
)

_DELETE_CONFIRM_KEYWORDS = ("да, удали", "да удали", "подтверждаю удаление", "да, удалить", "да удалить")


def is_delete_request(text: str) -> bool:
    """Первое, ещё не подтверждённое упоминание желания удалить данные —
    само по себе НЕ приводит к удалению (см. is_delete_confirmed ниже),
    только к переспросу с явным предупреждением о необратимости."""
    normalized = text.strip().lower()
    return any(keyword in normalized for keyword in _DELETE_REQUEST_KEYWORDS)


def is_delete_confirmed(text: str) -> bool:
    """Второе, уже явное подтверждение (после того, как бот уже
    предупредил о необратимости — см. DELETE_CONFIRMATION_PROMPT ниже) —
    только после этого реально вызывается candidates.delete_candidate()
    (см. assistant.py, где эта функция используется)."""
    normalized = text.strip().lower()
    return any(keyword in normalized for keyword in _DELETE_CONFIRM_KEYWORDS)


