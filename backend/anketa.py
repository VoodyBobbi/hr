# --- Вопрос "что я уже заполнил" посреди анкеты ----------------------------
#
# Раньше на это отвечал GigaChat (раздел "Как отвечать на вопросы про
# прогресс анкеты" в system_prompt.md, до переделки на стейт-машину) — сама
# модель вела диалог и знала контекст. Теперь GigaChat не участвует в ходе
# анкеты вообще (см. assistant.py:_handle_anketa_turn), поэтому без этой
# проверки такой вопрос ошибочно пытался бы сохраниться как ЗНАЧЕНИЕ
# текущего поля (например "а что я уже заполнил?" интерпретировалось бы как
# попытка ответить на вопрос про имя) — кандидат получал бы сообщение вида
# "это не похоже на имя, напишите ещё раз", что вводит в заблуждение.
_PROGRESS_QUESTION_KEYWORDS = (
    "что я уже заполнил", "что уже заполнил", "на чём мы остановились",
    "на чем мы остановились", "что осталось заполнить", "сколько осталось",
    "какой вопрос", "что дальше",
)


def is_progress_question(text: str) -> bool:
    normalized = text.strip().lower()
    return any(keyword in normalized for keyword in _PROGRESS_QUESTION_KEYWORDS)


def format_progress_answer(candidate_id: str) -> str:
    """Короткий человеческий ответ на вопрос о прогрессе — тот же стиль,
    что задавал прежний раздел промпта ("Пока указали фамилию и дату
    рождения — остальное ещё не заполняли"), просто собран кодом из уже
    сохранённых полей, а не сформулирован моделью по памяти."""
    card = candidates.get_card(candidate_id)
    filled = [field for field in _FIELD_ORDER_IN_ANKETA if card.get(field)]

    if not filled:
        return "Пока ничего не заполняли — начнём с первого вопроса."

    filled_list = ", ".join(filled)
    remaining = len(_FIELD_ORDER_IN_ANKETA) - len(filled)
    return f"Пока указали: {filled_list}. Осталось ещё {remaining} пункт(ов)."
