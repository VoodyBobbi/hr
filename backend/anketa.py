def format_status(candidate_id: str, stage: str) -> str:
    """Человеческий ответ о том, где кандидат находится сейчас.

    Текст зависит от этапа и от того, сколько полей уже заполнено. Никаких
    технических названий и процентов — только «вы здесь, делайте вот это»."""
    if stage == STAGE_DONE:
        return (
            "Ваша анкета уже заполнена и передана менеджеру — он свяжется "
            "с вами. Заполнять её заново не нужно. Если появились вопросы "
            "по работе, спрашивайте."
        )
    if stage == STAGE_LAW:
        return (
            "Чтобы начать анкету, нужно ваше согласие на обработку данных. "
            "Напишите «да», если согласны, или «нет», если не хотите."
        )
    if stage == STAGE_DELETE:
        return (
            "Сейчас жду подтверждения удаления данных. Напишите «да, удали», "
            "если уверены, или «нет», если передумали."
        )

    total = len(FIELD_NAMES)
    if candidates.is_card_complete(candidate_id):
        return (
            f"Все {total} пунктов заполнены — осталось только подтвердить. "
            f"Проверьте данные выше и напишите «да»."
        )

    step = get_next_step(candidate_id)
    if step is None:
        return "Анкета заполнена — осталось подтвердить, напишите «да»."

    filled = sum(1 for f in FIELD_NAMES if str(candidates.get_card(candidate_id).get(f, "")).strip())
    return (
        f"Вы заполняете анкету: готово {filled} из {total}.\n\n"
        f"Сейчас нужен ответ на вопрос: {step[1]}"
    )


def pending_field_options(candidate_id: str) -> list:
    """Варианты ответа для вопроса, который задан кандидату ПРЯМО СЕЙЧАС.

    Вызывается уже ПОСЛЕ обработки сообщения, когда анкета перешла к
    следующему полю, — то есть возвращает кнопки к тому вопросу, который
    кандидат видит в текущем ответе бота.

    Пустой список означает «кнопок нет, нужен свободный ввод»."""
    if not candidate_id:
        return []
    if candidates.get_stage(candidate_id) != STAGE_FIELDS:
        return []
    step = get_next_step(candidate_id)
    if not step:
        return []
    return list(FIELD_OPTIONS.get(step[0], []))


def parse_correction(text: str):
    """Разбирает строку вида «Телефон 89991234567» на (поле, значение).

    Возвращает None, если поле не распознано.

    Зачем. Бот обещает кандидату именно такой формат правки, но разбирать
    эту строку было НЕЧЕМ: код просто показывал карточку заново, правка
    пропадала, и выйти из этого круга было невозможно.

    Имя поля ищется В ЛЮБОМ МЕСТЕ строки, а не только в начале. Первая
    версия смотрела только на начало, и естественное «да, но телефон
    8999...» не распознавалось как правка — хуже того, слово «да» в начале
    закрывало анкету со старым номером, и HR не мог дозвониться.

    Из нескольких совпадений берётся САМОЕ ДЛИННОЕ имя: иначе «паспорт
    серия 4510» разобралось бы по короткому «паспорт» и откусило от
    значения слово «серия»."""
    normalized = text.strip()
    if not normalized:
        return None

    lowered = normalized.lower()

    # Кандидаты: (позиция начала значения, длина имени, поле).
    found = []
    names = list(_FIELD_ALIASES.items()) + [(f.lower(), f) for f in FIELD_NAMES]
    for name, field in names:
        for match in re.finditer(rf"\b{re.escape(name)}\b", lowered):
            value = normalized[match.end():].strip(" :=-—,.")
            if value:
                found.append((len(name), match.start(), field, value))

    if not found:
        return None

    # Сначала самое длинное имя, при равной длине — самое раннее в строке.
    found.sort(key=lambda item: (-item[0], item[1]))
    _, _, field, value = found[0]
    return field, value


def get_next_step(candidate_id: str):
    """Возвращает (field_name, question) для следующего незаполненного поля
    анкеты, либо None, если все 29 полей уже заполнены (анкета готова к
    показу итоговой карточки на подтверждение)."""
    card = candidates.get_card(candidate_id)
    for field in _FIELD_ORDER_IN_ANKETA:
        if not card.get(field):
            return field, _STEP_BY_FIELD[field][0]
    return None


def process_answer(candidate_id: str, field: str, raw_answer: str):
    """Обрабатывает ответ кандидата на вопрос текущего поля.

    Возвращает кортеж (ok: bool, message: str):
    - ok=True  -> поле сохранено, message — текст СЛЕДУЮЩЕГО вопроса (или
      финальное сообщение, если это было последнее из 29 полей).
    - ok=False -> поле НЕ сохранено (не прошло валидацию), message —
      дружелюбный текст ошибки для ЭТОГО ЖЕ поля (тот же вопрос кандидату
      предстоит увидеть ещё раз в следующем сообщении бота — см.
      assistant.py, где вызывается эта функция)."""
    try:
        clean_value = validate_field(field, raw_answer)
    except FieldValidationError:
        question, friendly_error = _STEP_BY_FIELD[field]
        # К тексту ошибки ОБЯЗАТЕЛЬНО добавляется сам вопрос. Иначе на
        # 29-м шаге подряд кандидат видит только «напишите цифрами» и не
        # помнит, о чём его вообще спрашивали — про рост, вес или размер
        # обуви. Раньше возвращался один текст ошибки, без вопроса.
        return False, f"{friendly_error}\n\n{question}"

    candidates.set_field(candidate_id, field, clean_value)

    next_step = get_next_step(candidate_id)
    if next_step is None:
        return True, None  # анкета полностью заполнена — дальше показ карточки, см. assistant.py
    _, next_question = next_step
    return True, next_question


def format_card_for_confirmation(candidate_id: str) -> str:
    """Формирует текст итоговой карточки анкеты для показа кандидату перед
    финальным подтверждением — тот же принцип, что раньше был в
    system_prompt.md ("Покажи ПОЛНУЮ карточку... попроси явного
    подтверждения ПЕРЕД CARD_CONFIRMED"), просто собран кодом из уже
    сохранённых полей, а не пересказан моделью по памяти (что исключает
    риск модели ошибочно исказить значение при пересказе)."""
    card = candidates.get_card(candidate_id)
    lines = ["Проверьте, пожалуйста, все данные:\n"]
    for field in _FIELD_ORDER_IN_ANKETA:
        lines.append(f"{field}: {card.get(field, '—')}")
    lines.append("\nВсё верно? Напишите «да» для подтверждения, либо укажите, что нужно исправить.")
    return "\n".join(lines)


# Слова, означающие "нужно что-то исправить" — проверяются ПЕРЕД согласием,
