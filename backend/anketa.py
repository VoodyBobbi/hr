def _contains_phrase(text: str, phrase: str) -> bool:
    """True, если phrase встречается в text как отдельное слово или
    словосочетание, а не как случайный кусок другого слова.

    re.escape нужен потому, что фразы могут содержать пробелы; \b по краям
    даёт границу слова. Для кириллицы это работает корректно: в Python 3
    модуль re по умолчанию в режиме Unicode, и русские буквы считаются
    словесными символами."""
    return re.search(rf"\b{re.escape(phrase)}\b", text) is not None


# Слова согласия, которые сами по себе ничего не значат: «давайте», «ок»,
# «хорошо» одинаково уместны и в «давайте начнём», и в «нет, давайте позже».
# Если рядом стоит отрицание или перенос на потом — это отказ, а не согласие.
_WEAK_ACCEPT_WORDS = {"давай", "давайте", "ок", "окей", "хорошо", "ага", "угу"}


def is_law_accepted(text: str) -> bool:
    """Явное согласие на обработку персональных данных.

    Три уровня проверки, и порядок между ними важен:

    1. Однозначный отказ («не согласен», «отказываюсь») — сразу нет.
    2. Отрицание или перенос рядом со СЛАБЫМ словом согласия. Фраза
       «Нет, давайте позже» раньше читалась как согласие: код видел слово
       «давайте» и на этом останавливался. Человек прямо отказался, а бот
       начинал требовать серию паспорта — то есть собирал персональные
       данные без согласия, вопреки 152-ФЗ.
    3. Всё остальное — обычный поиск слов согласия.
    """
    normalized = text.strip().lower()

    if any(_contains_phrase(normalized, phrase) for phrase in _STRONG_DECLINE_PHRASES):
        return False

    found_accept = [w for w in _ACCEPT_WORDS if _contains_phrase(normalized, w)]
    if not found_accept:
        return False

    # Есть ли рядом отрицание или перенос на потом.
    has_negation = any(_contains_phrase(normalized, w) for w in _WEAK_DECLINE_WORDS)
    # Осталось ли хоть одно СИЛЬНОЕ слово согласия («да», «согласен»,
    # «подтверждаю») — такое отрицанием не перебивается.
    has_strong_accept = any(w not in _WEAK_ACCEPT_WORDS for w in found_accept)

    if has_negation and not has_strong_accept:
        return False
    return True


def is_law_declined(text: str) -> bool:
    """Явный отказ от согласия — не классификатор намерения (это было бы
    задачей для ИИ, которого мы здесь сознательно не используем), а проверка
    на самые частые формулировки отказа.

    Всё, что не распознано ни как согласие, ни как отказ, приводит к
    повторному вопросу (LAW_CONSENT_RETRY в assistant.py), а НЕ к согласию по
    умолчанию, как было раньше."""
    normalized = text.strip().lower()
    if any(_contains_phrase(normalized, phrase) for phrase in _STRONG_DECLINE_PHRASES):
        return True
    if is_law_accepted(text):
        return False
    return any(_contains_phrase(normalized, word) for word in _WEAK_DECLINE_WORDS)


