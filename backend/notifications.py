"""
Уведомления HR-группе в Telegram о новых полностью заполненных анкетах.

Сделано отдельным лёгким модулем (прямой HTTP-запрос к Bot API через httpx),
а не через python-telegram-bot Application, по двум причинам:
1. Application — это тяжёлый объект с собственным event loop, рассчитанный
   на приём сообщений (long polling), а не просто на отправку одного
   сообщения. Поднимать его только ради одного sendMessage — избыточно.
2. Уведомление должно уходить одинаково, откуда бы ни пришла анкета — с
   сайта (backend/app.py) или из Telegram (backend/telegram_bot.py). Прямой
   HTTP-вызов к Bot API работает одинаково в обоих случаях; полноценный
   Application по устройству библиотеки привязан к процессу самого бота.

Уведомления отправляются ТЕМ ЖЕ ботом, что общается с кандидатами
(TELEGRAM_BOT_TOKEN — одна переменная на оба назначения: личные сообщения
кандидатам и сообщения в HR-группу) — просто в другую точку назначения
(chat_id HR-группы вместо chat_id конкретного кандидата). Заводить для
уведомлений отдельного второго бота нет смысла: боту всё равно нужны права
писать сообщения в HR-группу, второй токен не даёт здесь никакого выигрыша,
только лишнюю сущность для администрирования.

Как узнать TELEGRAM_HR_GROUP_CHAT_ID и как добавить бота в свою HR-группу —
см. README, раздел "Уведомления HR о новых заявках".
"""
import html
import os

import httpx

_API_URL_TEMPLATE = "https://api.telegram.org/bot{token}/sendMessage"


def _settings() -> tuple:
    """Токен бота и chat_id HR-группы, прочитанные В МОМЕНТ ОТПРАВКИ.

    Раньше обе переменные читались один раз при импорте модуля. Работало это
    только благодаря удачному порядку импортов: backend.paths вызывает
    load_dotenv() и импортируется по цепочке раньше, чем этот модуль. Стоило
    поменять порядок строк в assistant.py — и переменные читались бы из
    пустого окружения, а уведомления HR молча перестали бы приходить.
    Чтение при вызове убирает эту зависимость от порядка импортов
    насовсем."""
    return os.getenv("TELEGRAM_BOT_TOKEN"), os.getenv("TELEGRAM_HR_GROUP_CHAT_ID")


def hr_notifications_enabled() -> bool:
    """True, если заданы обе переменные, нужные для отправки уведомлений
    HR-группе. Если что-то не задано — уведомления просто тихо не
    отправляются (это НЕ обязательная функция: без Telegram-канала или без
    настроенной группы весь остальной бот должен продолжать работать)."""
    token, chat_id = _settings()
    return bool(token and chat_id)


def send_hr_notification(text: str) -> None:
    """Отправляет текстовое сообщение в HR-группу. Никогда не бросает
    исключение наружу — сбой уведомления не должен ронять сам ответ
    кандидату (это дополнительная, не критичная для работы бота функция)."""
    token, chat_id = _settings()
    if not (token and chat_id):
        return

    url = _API_URL_TEMPLATE.format(token=token)
    try:
        response = httpx.post(
            url,
            json={
                "chat_id": chat_id,
                "text": text,
                "parse_mode": "HTML",
            },
            timeout=10.0,
        )
        if response.status_code != 200:
            print(
                f"[notifications] Telegram Bot API вернул {response.status_code} "
                f"при отправке уведомления HR-группе: {response.text}. "
                f"Частая причина: TELEGRAM_HR_GROUP_CHAT_ID в .env неверный, "
                f"либо бот не добавлен в группу — см. README."
            )
    except httpx.HTTPError as e:
        print(f"[notifications] Не удалось отправить уведомление HR-группе: {e}")


def _esc(value) -> str:
    """Экранирует значение поля анкеты перед подстановкой в HTML-текст
    сообщения (parse_mode="HTML" в send_hr_notification выше). Без этого
    кандидат мог случайно (или намеренно) вписать в поле анкеты текст,
    похожий на HTML-тег (например незакрытый "<" в имени) — Telegram Bot
    API в ответ на невалидную разметку отклоняет ВСЁ сообщение целиком
    (см. send_hr_notification: response.status_code != 200), и HR тихо не
    узнаёт о новой заявке. html.escape() превращает "<", ">", "&" в их
    текстовые эквиваленты — сообщение всегда доходит, а спецсимволы
    показываются как есть, а не интерпретируются как разметка."""
    return html.escape(str(value)) if value else value


def format_new_candidate_notification(card: dict) -> str:
    """Формирует текст уведомления о новой полностью заполненной анкете.

    Намеренно НЕ включает чувствительные персональные данные — ни паспорт,
    СНИЛС, ИНН, адреса, НИ ТЕЛЕФОН (последний раньше ошибочно попадал сюда,
    хотя уже этот же комментарий заявлял, что чувствительные данные
    исключены — то есть код противоречил собственной декларации; телефон
    такие же персональные данные, как и остальное, просто не из числа
    самых чувствительных). Уведомление даёт HR ровно то, что нужно, чтобы
    узнать заявку и решить, открывать ли карточку кандидата — не более.
    Полная анкета целиком уже надёжно лежит в зашифрованном candidates.csv
    — дублировать любые личные данные в групповой чат Telegram (менее
    защищённый канал, доступный всем участникам группы, часто на личных
    телефонах без дополнительной защиты) было бы шагом назад по защите
    данных, а не вперёд.
    """
    full_name = " ".join(
        part for part in (card.get("Фамилия"), card.get("Имя"), card.get("Отчество")) if part
    ).strip() or "(ФИО не указано)"

    source_label = {"site": "сайт", "telegram": "Telegram"}.get(card.get("Источник"), card.get("Источник", "—"))
    law_ack = card.get("Факт ознакомления с ЗАКОНОМ", "").strip()
    law_status = "да, " + _esc(law_ack) if law_ack else "нет данных"

    return (
        f"<b>Новая заявка от кандидата</b>\n"
        f"ФИО: {_esc(full_name)}\n"
        f"Вакансия: {_esc(card.get('Желаемая должность', '—'))}\n"
        f"Канал обращения: {_esc(source_label)}\n"
        f"ID кандидата в таблице: {_esc(card.get('ID кандидата', '—'))}\n"
        f"Ознакомлен(а) с 152-ФЗ: {law_status}\n"
        f"\nПолная анкета (включая телефон и остальные поля) — в "
        f"зашифрованной таблице candidates.csv (id {_esc(card.get('ID кандидата', '—'))})."
    )
