"""
Балльная система ограничения по поведению — дополняет (не заменяет) простой
лимит slowapi в app.py (N запросов в минуту с одного IP).

Разница: slowapi ограничивает ЧИСЛО запросов, не заботясь о их содержании —
20 разных осмысленных вопросов за минуту проходят так же, как 20 одинаковых
спам-сообщений. Модуль ниже смотрит на ПАТТЕРН поведения одного собеседника
и начисляет баллы за подозрительные признаки:

- повтор одного и того же сообщения подряд: +2 балла
- слишком частые сообщения (быстрее REPEAT_WINDOW_SECONDS одно за другим): +2 балла
- аномально длинное сообщение (длиннее ANOMALOUS_LENGTH_CHARS символов): +1 балл

При достижении BLOCK_THRESHOLD баллов — блокировка на BLOCK_DURATION_MINUTES минут.
Баллы у каждого кандидата свои, не суммируются между разными людьми.

Хранение — в памяти процесса (обычный dict, не файл и не внешняя БД). Это
осознанное упрощение: uvicorn в этом проекте запускается БЕЗ --workers (один
процесс, см. run_all.py/start.sh) — единственный процесс сайта видит все
запросы, конфликта с несколькими воркерами нет. Если это изменится (сайт
начнёт запускаться с несколькими воркерами) — потребуется вынести хранение
в общее место (Redis, файл с блокировкой) — просто dict в памяти каждого
отдельного воркера видел бы только свою часть трафика.

Не хранится на диске и не переживает перезапуск сервера — это нормально
для защиты от спама-в-моменте, а не долгосрочного учёта: перезапуск сервера
и так сбрасывает подозрительную активность, это не персональные данные,
которые нужно беречь между перезапусками.
"""
import threading
import time

# --- Настраиваемые пороги -----------------------------------------------
#
# Значения подобраны так, чтобы НЕ мешать заполнению анкеты. Это главный
# сценарий, который прежние настройки ломали: кандидат отвечает на 29
# вопросов подряд короткими репликами ("Иванов", "12.04.1988", "нет"), и
# каждый ответ приходил быстрее чем через 5 секунд после предыдущего.
# Начислялось по 2 балла, порог был 5, баллы НИКОГДА не убывали — на
# третьем-четвёртом поле анкеты человек получал блокировку на 5 минут.
# Ровно это и происходило: "Вы отправляете сообщения слишком часто" сразу
# после даты рождения.
FAST_REPLY_SECONDS = 1.5         # быстрее этого между сообщениями = машинный темп
ANOMALOUS_LENGTH_CHARS = 1500    # длиннее этого = аномальная длина
BLOCK_THRESHOLD = 8              # баллов для блокировки
BLOCK_DURATION_MINUTES = 2

REPEAT_MESSAGE_POINTS = 2
HIGH_FREQUENCY_POINTS = 1
ANOMALOUS_LENGTH_POINTS = 1

# За сколько секунд «сгорает» один балл. Без затухания баллы копились за всю
# жизнь процесса: человек, спокойно поговоривший с ботом несколько раз за
# день, рано или поздно набирал порог и получал блокировку ни за что.
# Спам отличается от нормального диалога не общим числом сообщений, а их
# ПЛОТНОСТЬЮ во времени — затухание как раз это и выражает.
POINT_DECAY_SECONDS = 20.0


_lock = threading.Lock()

# key -> {"last_message": str, "last_time": float, "points": float, "blocked_until": float}
_state: dict[str, dict] = {}


def _key(source: str, external_id: str) -> str:
    """Ключ счётчика.

    Что подставляется вторым аргументом, решает вызывающий код, и это разное
    для двух каналов: Telegram передаёт chat_id (подделать его пользователь
    не может), сайт — идентификатор сессии браузера.

    По IP-адресу сайт НЕ считает намеренно: за одним внешним адресом сидят
    офис с общим интернетом, кафе с бесплатным Wi-Fi или целый район на NAT
    мобильного оператора. Их сообщения сливаются в один плотный поток, и
    счётчик блокировал бы сразу всех за то, чего никто не делал. От обхода
    через очистку cookie защищает отдельный лимит запросов в минуту с одного
    IP (slowapi, см. backend/app.py) — он ограничивает ущерб, не выключая
    бота для целой сети."""
    return f"{source}:{external_id}"


def is_blocked(source: str, external_id: str) -> tuple[bool, float]:
    """Возвращает (заблокирован_ли_сейчас, секунд_до_снятия_блокировки).
    Вторая часть кортежа осмысленна только при заблокирован_ли_сейчас=True."""
    key = _key(source, external_id)
    with _lock:
        entry = _state.get(key)
        if not entry:
            return False, 0.0
        blocked_until = entry.get("blocked_until", 0.0)
        now = time.time()
        if blocked_until > now:
            return True, blocked_until - now
        return False, 0.0


def record_message(source: str, external_id: str, message: str,
                   block_threshold: int = BLOCK_THRESHOLD) -> None:
    """Начисляет баллы за текущее сообщение и, если порог достигнут,
    устанавливает блокировку.

    Вызывается ПОСЛЕ is_blocked (см. app.py и telegram_bot.py), поэтому
    сообщение, которое довело счётчик до порога, само ещё проходит, а
    блокируется уже следующее.

    Три признака, за которые начисляются баллы:

    - повтор ровно того же текста, причём ТОЛЬКО если он пришёл быстро.
      Проверка времени здесь принципиальна: в анкете кандидат совершенно
      законно отвечает "нет" на три вопроса про судимости подряд, и раньше
      это давало 6 баллов из 5 нужных для блокировки;
    - машинный темп — меньше FAST_REPLY_SECONDS между сообщениями. Человек
      физически не набирает осмысленный текст быстрее;
    - аномальная длина — попытка забить контекст модели.

    Перед начислением баллы уменьшаются на прошедшее время
    (POINT_DECAY_SECONDS на балл), поэтому обычный разговор с паузами
    счётчик не накапливает."""
    key = _key(source, external_id)
    now = time.time()

    with _lock:
        entry = _state.setdefault(
            key, {"last_message": "", "last_time": 0.0, "points": 0.0, "blocked_until": 0.0}
        )

        # Затухание: сколько баллов «сгорело» с прошлого сообщения.
        if entry["last_time"]:
            elapsed = now - entry["last_time"]
            entry["points"] = max(0.0, entry["points"] - elapsed / POINT_DECAY_SECONDS)

        gap = now - entry["last_time"] if entry["last_time"] else None
        is_fast = gap is not None and gap < FAST_REPLY_SECONDS

        points_added = 0
        if is_fast and entry["last_message"] and message == entry["last_message"]:
            points_added += REPEAT_MESSAGE_POINTS
        if is_fast:
            points_added += HIGH_FREQUENCY_POINTS
        if len(message) > ANOMALOUS_LENGTH_CHARS:
            points_added += ANOMALOUS_LENGTH_POINTS

        entry["points"] += points_added
        entry["last_message"] = message
        entry["last_time"] = now

        if entry["points"] >= block_threshold:
            entry["blocked_until"] = now + BLOCK_DURATION_MINUTES * 60
            entry["points"] = 0.0


def in_anketa(source: str, external_id: str) -> bool:
    """True, если собеседник сейчас заполняет анкету.

    На время анкеты счётчик спама отключается (см. app.py и telegram_bot.py).
    Причина: шаги анкеты обрабатывает обычный код, GigaChat не вызывается, и
    денег такие сообщения не стоят — защищать тут нечего. Зато мешает счётчик
    сильно: кандидат вставляет данные из буфера обмена, отправляет две части
    подряд, дважды жмёт «Отправить», решив что не ушло, — и получает
    блокировку на середине анкеты, теряя нить.

    Импорт внутри функции, а не сверху файла: candidates тянет за собой
    шифрование и работу с файлами, а rate_limiting должен оставаться
    лёгким модулем без тяжёлых зависимостей на уровне импорта."""
    from . import anketa, candidates

    candidate_id = candidates.find_candidate(source, external_id)
    if not candidate_id:
        return False
    return candidates.get_stage(candidate_id) in (
        anketa.STAGE_LAW, anketa.STAGE_FIELDS, anketa.STAGE_CONFIRM, anketa.STAGE_DELETE,
    )
