"""
Единая команда установки И запуска проекта:

    python start.py

Раньше нужно было запускать две команды по отдельности:
    python setup.py    — установка зависимостей + генерация ключа шифрования
    python run_all.py  — сборка/обновление индекса, чистка логов, запуск
                          сайта и Telegram-бота

start.py просто вызывает их одну за другой в одном процессе — сам не
дублирует и не меняет их логику. Старые команды (setup.py, run_all.py)
по отдельности продолжают работать как раньше, это ничего не ломает.

Безопасность порядка вызова: и setup.py, и run_all.py на верхнем уровне
файла импортируют только стандартную библиотеку (os, subprocess, sys) —
внешние зависимости (dotenv, cryptography, faiss, sentence-transformers)
импортируются лениво, внутри функций, уже ПОСЛЕ того как setup.main()
их установит. Поэтому импортировать оба модуля в начале этого файла можно
даже на полностью чистом окружении, где зависимости ещё не поставлены.
"""
import setup
import run_all


def main():
    setup.main()
    print()
    run_all.main()


if __name__ == "__main__":
    main()
