"""
ЕДИНСТВЕННАЯ команда для установки и запуска проекта:

    python start.py

Делает всё подряд, за один заход:

1. Ставит зависимости из requirements.txt.
2. Устанавливает сертификат НУЦ Минцифры — без него запрос к GigaChat
   падает с ошибкой "[SSL: CERTIFICATE_VERIFY_FAILED] self-signed
   certificate in certificate chain", и бот отвечает только на те вопросы,
   для которых есть готовый ответ в faqs.json.
3. Создаёт .env из .env.example, если его ещё нет.
4. Генерирует ключ шифрования анкет (ENCRYPTION_KEY), если он пустой.
   Заполненный ключ НЕ трогает — иначе уже собранные анкеты стали бы
   нечитаемыми.
5. Пересобирает поисковые индексы, если data/ менялась.
6. Чистит логи старше срока хранения.
7. Запускает сайт и Telegram-бота.
8. Показывает ключ шифрования, чтобы его можно было сохранить.

Повторные запуски проходят быстро: шаги 1–4 видят, что всё уже сделано, и
пропускают работу, шаг 5 сверяет хеш и пересобирает индекс только если
файлы в data/ действительно менялись.

setup.py и run_all.py по-прежнему можно вызывать по отдельности — эта
команда их не заменяет, а просто вызывает одну за другой. Своей логики
здесь нет намеренно: два способа сделать одно и то же неизбежно
разъезжаются при первой же правке.

Порядок вызова безопасен на чистом окружении. И setup.py, и run_all.py на
верхнем уровне импортируют только стандартную библиотеку (os, subprocess,
sys), а внешние зависимости (dotenv, cryptography, faiss,
sentence-transformers) импортируют лениво, внутри функций — уже ПОСЛЕ того
как setup.main() их установит.
"""
import setup
import run_all


def main():
    # standalone=False убирает из setup.py хвост "теперь выполните
    # python run_all.py": здесь запуск идёт следующей же строкой, и такая
    # подсказка выглядела бы как требование второй команды.
    setup.main(standalone=False)
    run_all.main()


if __name__ == "__main__":
    main()
